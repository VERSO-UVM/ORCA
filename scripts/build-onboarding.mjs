// Builds the Onboarding section of index.html from onboarding/tasks/*.md.
//
//   node scripts/build-onboarding.mjs          rewrite index.html
//   node scripts/build-onboarding.mjs --check  exit 1 if index.html is out of date
//
// Runs with Node 18+ or Bun, with no dependencies. Task files use the header
// and the small Markdown subset described in onboarding/README.md.

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { GROUPS, FOCUS, FOCUS_LABEL, readTasks } from "./onboarding-tasks.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PAGE = join(ROOT, "index.html");
const REPO_BLOB = "https://github.com/VERSO-UVM/ORCA/blob/main/";
const START = "<!-- ONBOARDING:START (generated by scripts/build-onboarding.mjs from onboarding/tasks; do not edit by hand) -->";
const END = "<!-- ONBOARDING:END -->";

// ---------- Markdown subset ----------

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function href(url) {
  if (url.startsWith("../README.md#how-to-finish-a-task")) return { url: "#ob-how-to-finish", external: false };
  if (/^https?:\/\//.test(url)) return { url, external: true };
  if (url.startsWith("#")) return { url, external: false };
  // A path relative to onboarding/tasks/: link to the file on GitHub.
  const parts = ["onboarding", "tasks"];
  for (const p of url.split("/")) {
    if (p === "..") parts.pop();
    else if (p !== ".") parts.push(p);
  }
  return { url: REPO_BLOB + parts.join("/"), external: true };
}

function inline(text) {
  const codes = [];
  let s = esc(text).replace(/`([^`]+)`/g, (_, c) => `\u0000${codes.push(c) - 1}\u0000`);
  s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, label, url) => {
    const h = href(url.replace(/&amp;/g, "&"));
    const extra = h.external ? ' target="_blank" rel="noopener"' : "";
    return `<a href="${esc(h.url)}"${extra}>${label}</a>`;
  });
  s = s.replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
  return s.replace(/\u0000(\d+)\u0000/g, (_, i) => `<code>${codes[i]}</code>`);
}

function markdown(md) {
  const out = [];
  let para = [];
  let list = null; // { tag, items: [] }
  const flushPara = () => {
    if (para.length) out.push(`<p>${inline(para.join(" "))}</p>`);
    para = [];
  };
  const flushList = () => {
    if (list) out.push(`<${list.tag}${list.start}>${list.items.map((i) => `<li>${inline(i)}</li>`).join("")}</${list.tag}>`);
    list = null;
  };
  for (const line of md.split("\n")) {
    const heading = line.match(/^##\s+(.*)$/);
    const ul = line.match(/^[-*]\s+(.*)$/);
    const ol = line.match(/^(\d+)\.\s+(.*)$/);
    if (!line.trim()) { flushPara(); flushList(); }
    else if (heading) { flushPara(); flushList(); out.push(`<h4>${inline(heading[1])}</h4>`); }
    else if (ul || ol) {
      flushPara();
      const tag = ul ? "ul" : "ol";
      if (!list || list.tag !== tag) {
        flushList();
        const n = ol ? Number(ol[1]) : 1;
        list = { tag, start: ol && n !== 1 ? ` start="${n}"` : "", items: [] };
      }
      list.items.push(ul ? ul[1] : ol[2]);
    } else if (list && /^\s+\S/.test(line)) list.items[list.items.length - 1] += " " + line.trim();
    else { flushList(); para.push(line.trim()); }
  }
  flushPara();
  flushList();
  return out.join("\n");
}

// ---------- Page ----------

function forLabel(t) {
  if (t.for.length === 2) return "New and returning";
  return t.for[0] === "new" ? "New students" : "Returning students";
}

function minutesLabel(m) {
  if (m < 60) return `${m} min`;
  const h = Math.floor(m / 60), r = m % 60;
  return r ? `${h} h ${r} min` : `${h} h`;
}

function taskHtml(t) {
  const anchor = `ob-${t.id.toLowerCase()}`;
  const tags = [
    forLabel(t),
    t.areas.includes("all") ? null : t.areas.map((a) => FOCUS_LABEL[a]).join(", "),
    t.lead ? "Pod leads" : null,
    t.skippable ? "Skip if you know it" : null,
    t.status === "draft" ? "Draft" : null,
    t.status === "retired" ? "Retired" : null,
  ].filter(Boolean);
  return `            <details class="ob-task${t.status === "retired" ? " ob-retired" : ""}" id="${anchor}" data-for="${t.for.join(" ")}" data-areas="${t.areas.join(" ")}" data-lead="${t.lead}" data-status="${t.status}" data-minutes="${t.minutes}">
              <summary>
                <span class="ob-task-id">${t.id}</span>
                <span class="ob-task-title">${esc(t.title)}</span>
                <span class="ob-task-meta"><span class="ob-tag">About ${minutesLabel(t.minutes)}</span>${tags.map((x) => `<span class="ob-tag">${esc(x)}</span>`).join("")}</span>
              </summary>
              <div class="ob-task-body">
${markdown(t.body).split("\n").map((l) => "                " + l).join("\n")}
                <p class="ob-task-link"><a class="ob-copy" href="#${anchor}" data-id="${t.id}">Copy link to ${t.id}</a></p>
              </div>
            </details>`;
}

// The "How to finish a task" box. The form link lives in onboarding/config.json.
function finishHtml() {
  const config = JSON.parse(readFileSync(join(ROOT, "onboarding", "config.json"), "utf8"));
  const form = config.reflectionForm;
  if (!form) {
    return `          <p>The reflection form for onboarding opens soon. Until then, start a task with the <a href="https://github.com/VERSO-UVM/ORCA/issues/new/choose" target="_blank" rel="noopener">onboarding issue form</a> as before.</p>`;
  }
  return `          <p>When you finish a task, send it with the <a href="${esc(form)}" target="_blank" rel="noopener"><strong>reflection form</strong></a>. Sign in with your NetID, choose the task's ID, and answer three questions:</p>
          <ul>
            <li><strong>What I did</strong></li>
            <li><strong>What I learned</strong></li>
            <li><strong>One question, or one thing I'd change</strong></li>
          </ul>
          <p>Some tasks ask for one more thing, such as your ORCiD or a pull request link; the form has a box for it. Admin tasks only need "done". Only ORCA staff see your answers. <strong>Never put ID documents, bank details or passwords in the form.</strong></p>`;
}

function sectionHtml(tasks) {
  const groups = GROUPS.map((g) => ({ ...g, tasks: tasks.filter((t) => t.id.startsWith(g.area + "-")) })).filter((g) => g.tasks.length);
  const focus = FOCUS.map((f) => `              <label class="ob-chip"><input type="checkbox" name="ob-area" value="${f.key}"> ${f.label}</label>`).join("\n");
  const body = groups.map((g) => `          <div class="ob-group" data-area="${g.area}">
            <h3 class="ob-group-title">${g.title}</h3>
            <p class="ob-group-note">${g.note}</p>
${g.tasks.map(taskHtml).join("\n")}
          </div>`).join("\n");
  return `${START}
    <section class="onboarding section" id="onboarding" aria-labelledby="onboarding-heading">
      <div class="container">
        <div class="section-intro">
          <p class="section-label">Onboarding</p>
          <h2 class="section-heading" id="onboarding-heading">Your first weeks at ORCA.</h2>
          <p class="section-sub">Every onboarding task, each with its own link. Choose your focus areas and whether you are new or returning to see your path in order.</p>
        </div>

        <form class="ob-picker" id="ob-picker" hidden>
          <fieldset>
            <legend>I am</legend>
            <div class="ob-chips">
              <label class="ob-chip"><input type="radio" name="ob-status" value="new" checked> New to ORCA</label>
              <label class="ob-chip"><input type="radio" name="ob-status" value="returning"> Returning</label>
              <label class="ob-chip"><input type="checkbox" name="ob-lead" value="lead"> I lead a Pod</label>
            </div>
          </fieldset>
          <fieldset>
            <legend>My work this semester <span class="ob-legend-note">(choose any)</span></legend>
            <div class="ob-chips">
${focus}
            </div>
          </fieldset>
          <p class="ob-count" id="ob-count" role="status" aria-live="polite"></p>
          <button type="button" class="ob-show-all" id="ob-show-all">Show every task</button>
        </form>
        <p class="ob-sr-only" id="ob-announce" aria-live="polite"></p>

        <div class="ob-finish" id="ob-how-to-finish">
          <h3>How to finish a task</h3>
${finishHtml()}
        </div>

        <div class="ob-tasks" id="ob-tasks">
${body}
        </div>

        <div class="pods-footer">
          <a href="https://github.com/VERSO-UVM/ORCA/tree/main/onboarding" target="_blank" rel="noopener" class="text-link">Fix or add a task on GitHub →</a>
        </div>
      </div>
    </section>
    ${END}`;
}

// ---------- Main ----------

const tasks = readTasks();

const page = readFileSync(PAGE, "utf8");
const eol = page.includes("\r\n") ? "\r\n" : "\n";
const s = page.indexOf(START.slice(0, 22));
const e = page.indexOf(END);
if (s < 0 || e < s) {
  console.error(`index.html needs the two marker comments: "${START.slice(0, 22)}..." and "${END}"`);
  process.exit(1);
}
const next = page.slice(0, s) + sectionHtml(tasks).replace(/\n/g, eol) + page.slice(e + END.length);

if (process.argv.includes("--check")) {
  if (next !== page) {
    console.error("index.html is out of date. Run: node scripts/build-onboarding.mjs");
    process.exit(1);
  }
  console.log(`index.html is up to date (${tasks.length} tasks).`);
} else {
  writeFileSync(PAGE, next);
  console.log(`Wrote ${tasks.length} tasks into index.html.`);
}
